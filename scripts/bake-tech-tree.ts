// Bake the tech-tree roster from the OW reference XML, so a picker over a tech
// column can offer the techs a player actually researches.
//
// tech.xml holds two kinds of entry under one <zType> space. 49 are the techs
// on the tree. The other 66 are the bonus and upgrade cards a tech hands out
// (TECH_STONECUTTING_BONUS_STONE, TECH_SHIP_UPGRADE) — real TechTypes that a
// save records and `tech_events` stores, but never a research choice.
//
// The tree's own node test is `player?.isTechHide(tech) ?? tech.mbHide`, in
// `TechTreePanel.BuildTreeLayout` (TechTreePanel.cs:649, the decompiled
// client): a tech that answers true is skipped and gets no node.
// `Player.isTechHide` (Player.cs:20529) is `mbHide || !isTechValid`, so the
// part of it that does not depend on a player's own game is `mbHide`.
//
// The filter here is `!mbDisable && !mbHide`, which is the test
// `Game.randomizeTechs`'s local `isTechShown` (Game.cs:8274) applies — that
// function remaps prereqs within a column rather than filling the tree, so it
// is a second reader of the same flags and not the tree itself. Both select the
// same 49 in this build: of tech.xml's 115 entries, 66 carry <bHide> and the 3
// that carry <bDisable> all carry <bHide> too, so no entry is separated by
// `mbDisable` alone.
//
// NOT <iColumn>: it separates the same 49 in this build only by accident,
// because `miColumn` defaults to 0 (InfoTech, InfoBase.cs:6686) and a bonus
// card omitting the tag is indistinguishable at runtime from a column-0 tech
// like TECH_IRONWORKING.
//
// Why this is not TECH_NAMES: that table is the display-name DIVERGENCES, 66
// of whose 67 keys are bonus cards, and TECH_BATTLELINE is the only tree tech
// in it (`techName` falls through to formatEnum for the other 48). A roster
// cannot be read off it.
//
// SOURCE (local-only, via the Reference/ symlink resolved by paths.ts):
//   Reference/XML/Infos/tech.xml — <Entry> with <zType>, <bHide>, <bDisable>,
//   <iColumn>, <iRow>. The leading <Entry> is a blank schema template
//   (<zType/> empty) and is excluded.
//
// OUTPUT: src/lib/generated/tech-tree.ts (checked in, self-contained — no
// .bake sidecar, so bake:finalize never blanks it in a checkout where this
// hasn't run; the arrangement bake-starting-techs.ts uses).
//
// Order is the payload: column then row, which is the tree read left to right.
// A caller that wants it by display name sorts at the call site, the way
// $lib/query/vocabularies does.
//
// Run: npm run bake:tech-tree

import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { XMLParser } from "fast-xml-parser";
import { format as prettierFormat, resolveConfig } from "prettier";

import { resolveReferenceXml } from "./lib/paths.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const OUTPUT_TS = resolve(REPO_ROOT, "src/lib/generated/tech-tree.ts");

const PREFIX = "TECH_";

interface Entry {
	zType?: string;
	bHide?: string;
	bDisable?: string;
	iColumn?: string;
	iRow?: string;
}

const parser = new XMLParser({
	ignoreAttributes: true,
	parseTagValue: false,
	ignoreDeclaration: true,
	ignorePiTags: true,
});

// The XML writes a true flag as 1 and omits it otherwise; the game's reader
// defaults every bool to false (InfoBase.cs).
const flag = (raw: string | undefined): boolean => raw === "1";

// <iColumn>/<iRow> are optional and default to 0, as miColumn/miRow do.
const int = (raw: string | undefined): number => {
	const n = Number(raw);
	return Number.isFinite(n) ? n : 0;
};

async function main(): Promise<void> {
	const path = resolve(resolveReferenceXml(), "Infos", "tech.xml");
	const parsed = parser.parse(await readFile(path, "utf-8")) as {
		Root?: { Entry?: Entry | Entry[] };
	};
	const entry = parsed.Root?.Entry;
	const entries = entry == null ? [] : Array.isArray(entry) ? entry : [entry];

	const shown = entries
		.filter(
			(e): e is Entry & { zType: string } =>
				typeof e.zType === "string" &&
				e.zType.startsWith(PREFIX) &&
				!flag(e.bHide) &&
				!flag(e.bDisable),
		)
		.sort(
			(a, b) => int(a.iColumn) - int(b.iColumn) || int(a.iRow) - int(b.iRow),
		)
		.map((e) => e.zType);

	if (shown.length === 0) {
		throw new Error(
			"bake-tech-tree: tech.xml yielded no shown techs — the XML shape changed",
		);
	}

	const lines = [
		"// AUTO-GENERATED by scripts/bake-tech-tree.ts. Do not edit.",
		"// Run `npm run bake:tech-tree` to refresh from Reference/XML.",
		"",
		"// The techs on the tech tree, in column-then-row order. The bonus and",
		"// upgrade cards a tech hands out are TechTypes too and are not here:",
		"// the tree draws no node for a tech whose `mbHide` is set",
		"// (`player?.isTechHide(tech) ?? tech.mbHide`,",
		"// TechTreePanel.BuildTreeLayout), and this filter also drops",
		"// `mbDisable`, which no entry in this build sets on its own.",
		"//",
		"// A roster only — `techName` ($lib/game-detail/helpers) is the label.",
		"export const TREE_TECHS: readonly string[] = [",
		...shown.map((z) => `\t"${z}",`),
		"];",
		"",
	];

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(lines.join("\n"), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-tech-tree: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-tech-tree: ${shown.length} techs → ${OUTPUT_TS.replace(REPO_ROOT + "/", "")}`,
	);
}

await main();
