// Bake the family-class roster from the OW reference XML, so a picker over a
// family-class column can offer the game's own list instead of a typed token.
//
// The explore surface filters two columns on this roster —
// `player_summaries.capital_family_class` and
// `player_family_cities.family_class` (cloud/src/query/catalog.ts) — and had no
// list to offer for either. Nothing in src/lib/generated/ held one:
// FAMILY_COLORS is keyed by FAMILY_* (a family is per-nation; its class is
// not), and the FAMILYCLASS_ keys in crest-sprites.ts are crest names with a
// _SEAT variant each, not the roster.
//
// Every class names itself TEXT_<zType>, and the en-US text matches
// formatEnum() output ("Landowners", "Champions"), so there is no name table
// here — only the roster. `formatEnum(value, "FAMILYCLASS_")` is the label.
//
// SOURCE (local-only, via the Reference/ symlink resolved by paths.ts):
//   Reference/XML/Infos/familyClass.xml — <Entry> with <zType> (FAMILYCLASS_*).
//   The leading <Entry> is a blank schema template (<zType/> empty) and is
//   excluded.
//
// OUTPUT: src/lib/generated/family-classes.ts (checked in, self-contained —
// no .bake sidecar, so bake:finalize never blanks it in a checkout where this
// hasn't run; the arrangement bake-starting-techs.ts uses).
//
// Order is the payload: document order is the game's own, and the array is
// emitted verbatim rather than sorted. A caller that wants it by display name
// sorts at the call site, the way $lib/query/vocabularies does.
//
// Run: npm run bake:family-classes

import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { XMLParser } from "fast-xml-parser";
import { format as prettierFormat, resolveConfig } from "prettier";

import { resolveReferenceXml } from "./lib/paths.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const OUTPUT_TS = resolve(REPO_ROOT, "src/lib/generated/family-classes.ts");

const PREFIX = "FAMILYCLASS_";

interface Entry {
	zType?: string;
}

const parser = new XMLParser({
	ignoreAttributes: true,
	parseTagValue: false,
	ignoreDeclaration: true,
	ignorePiTags: true,
});

async function main(): Promise<void> {
	const path = resolve(resolveReferenceXml(), "Infos", "familyClass.xml");
	const parsed = parser.parse(await readFile(path, "utf-8")) as {
		Root?: { Entry?: Entry | Entry[] };
	};
	const entry = parsed.Root?.Entry;
	const entries = entry == null ? [] : Array.isArray(entry) ? entry : [entry];

	const classes = entries
		.map((e) => e.zType)
		.filter((z): z is string => typeof z === "string" && z.startsWith(PREFIX));

	if (classes.length === 0) {
		throw new Error(
			"bake-family-classes: familyClass.xml yielded no FAMILYCLASS_ entries — " +
				"the XML shape changed",
		);
	}

	const lines = [
		"// AUTO-GENERATED by scripts/bake-family-classes.ts. Do not edit.",
		"// Run `npm run bake:family-classes` to refresh from Reference/XML.",
		"",
		"// The family classes the game declares (familyClass.xml), in its own",
		"// order. A roster only: every class names itself TEXT_<zType> and the",
		'// text matches formatEnum(value, "FAMILYCLASS_"), so there is no name',
		"// table to go with it.",
		"export const FAMILY_CLASSES: readonly string[] = [",
		...classes.map((z) => `\t"${z}",`),
		"];",
		"",
	];

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(lines.join("\n"), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-family-classes: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-family-classes: ${classes.length} family classes → ${OUTPUT_TS.replace(REPO_ROOT + "/", "")}`,
	);
}

await main();
