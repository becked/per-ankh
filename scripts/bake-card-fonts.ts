// Bake the two static Inter instances the OG card's rasterizer needs, from
// the same variable WOFF2 the app serves.
//
// SOURCE: static/fonts/InterVariable-latin-opsz.woff2 — the face src/app.css
// declares for the whole UI, and the one the card is a render of. Checked in,
// so this baker needs neither a pinacotheca checkout nor Reference/XML.
//
// WHY A BAKE AND NOT THE WOFF2 ITSELF: resvg takes font bytes through
// `font.fontBuffers` and reads WOFF2 fine, but it has no variable-font
// support — a variable face renders at its default instance whatever
// `font-weight` the SVG asks for, so bold and regular come out identical.
// (Verified against @resvg/resvg-wasm 2.6.2 before this baker existed.)
// Pinning `wght` produces a genuinely static face per weight, and harfbuzz
// writes the pinned weight into OS/2 usWeightClass, which is what lets resvg
// pick between the two from `font-weight`.
//
// THE TWO WEIGHTS are the two the card draws: 400 for the save-date chip and
// 700 for everything else (RecentSaveCard.svelte — every other string in it is
// `font-bold`).
//
// `opsz` is pinned at its own default, 14. Inter's optical-size axis starts
// there and Chrome drives it from font-size, so the browser renders the card's
// 10-14px type at exactly opsz 14 too; the card's larger type is the only
// place the two diverge, by the tracking difference src/app.css measures
// (1.6% at 16px). Pinning it is what drops `fvar`/`gvar` and makes the output
// a plain static TTF.
//
// THE CHARACTER SET is read off the source font rather than guessed: the
// subset keeps every codepoint the WOFF2 covers, so the Worker draws exactly
// what the browser would. A codepoint outside it has no fallback face in the
// Worker (`loadSystemFonts: false`) and renders blank — the same set the
// browser would hand to its platform fallback.
//
// OUTPUT: cloud/src/generated/card-fonts.ts (checked in, self-contained).
// Base64 rather than two .ttf files: the Worker reads them as bytes at module
// scope, a generated TS module is the shape every other `cloud/src/generated/`
// entry already has, and it needs no `[[rules]]` block in wrangler.toml to
// bundle.
//
// Run: npm run bake:card-fonts

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as fontkit from "fontkit";
import { format as prettierFormat, resolveConfig } from "prettier";
import subsetFont from "subset-font";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const SOURCE_WOFF2 = resolve(
	REPO_ROOT,
	"static/fonts/InterVariable-latin-opsz.woff2",
);
const OUTPUT_TS = resolve(REPO_ROOT, "cloud/src/generated/card-fonts.ts");

// The axis values each instance pins. `opsz` is the axis default; `wght` is
// the card's two weights.
const OPTICAL_SIZE = 14;
const WEIGHTS = [400, 700] as const;

function base64(bytes: Uint8Array): string {
	return Buffer.from(bytes).toString("base64");
}

// Every codepoint the source face maps, as the string subset-font takes.
// Surrogate halves are not codepoints and `characterSet` does not emit them;
// anything outside the BMP still round-trips through `fromCodePoint`.
function sourceCharacterSet(woff2: Buffer): string {
	const font = fontkit.create(woff2);
	if (!("characterSet" in font)) {
		throw new Error(
			`bake-card-fonts: ${SOURCE_WOFF2} is a font collection, not a single face`,
		);
	}
	return font.characterSet.map((cp) => String.fromCodePoint(cp)).join("");
}

async function main(): Promise<void> {
	if (!existsSync(SOURCE_WOFF2)) {
		throw new Error(`bake-card-fonts: source font missing: ${SOURCE_WOFF2}`);
	}
	const woff2 = await readFile(SOURCE_WOFF2);
	const chars = sourceCharacterSet(woff2);

	const instances: Array<{ weight: number; bytes: Uint8Array }> = [];
	for (const weight of WEIGHTS) {
		const bytes = await subsetFont(woff2, chars, {
			targetFormat: "sfnt",
			variationAxes: { wght: weight, opsz: OPTICAL_SIZE },
		});
		instances.push({ weight, bytes });
	}

	const lines: string[] = [];
	lines.push("// AUTO-GENERATED by scripts/bake-card-fonts.ts. Do not edit.");
	lines.push("// Run `npm run bake:card-fonts` to refresh from static/fonts/.");
	lines.push("");
	lines.push("// Static Inter instances for the OG card rasterizer, pinned at");
	lines.push(
		`// opsz ${OPTICAL_SIZE} and the weight named, base64-encoded. resvg has no variable-font`,
	);
	lines.push(
		"// support, so the two weights have to be two faces; both report family",
	);
	lines.push('// "Inter", and resvg picks between them on the SVG\'s');
	lines.push("// `font-weight`. See the baker for the full rationale.");
	lines.push(
		`// ${chars.length} codepoints each, the source WOFF2's whole coverage.`,
	);
	lines.push("");
	lines.push('export const CARD_FONT_FAMILY = "Inter";');
	lines.push("");
	for (const { weight, bytes } of instances) {
		lines.push(
			`// ${bytes.length.toLocaleString("en-US")} bytes before base64.`,
		);
		lines.push(
			`export const CARD_FONT_${weight}_BASE64 = ${JSON.stringify(base64(bytes))};`,
		);
		lines.push("");
	}

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(lines.join("\n"), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-card-fonts: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-card-fonts: ${instances
			.map((i) => `wght ${i.weight} ${i.bytes.length} bytes`)
			.join(
				", ",
			)}, ${chars.length} codepoints → ${OUTPUT_TS.replace(REPO_ROOT + "/", "")}`,
	);
}

await main();
