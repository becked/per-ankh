// Bake the PROMOTION_<zType> → English display name table from the OW
// reference XML so a unit's promotions read as the game names them.
//
// formatEnum() strips a trailing digit and title-cases the rest, which is
// wrong for every tiered promotion line: the game calls them Combat I / II /
// III, and formatEnum gives "Combat1". That is 12 of the 41 promotions —
// Combat, Strike, Guard and Focus, three tiers each — and they are the common
// ones, so the table is not a corner case.
//
// SOURCES (local-only, via the Reference/ symlink resolved by paths.ts), under
// Reference/XML/Infos/:
//   promotion.xml  — <Entry> with <zType> and <Name>, a TEXT_PROMOTION_* key.
//     A plain <Name> rather than the <GenderedName> indirection nation.xml
//     uses, so no genderedText.xml walk is needed here.
//   text-*.xml     — <Entry> with that <zType> and an <en-US> string, split
//     across the base and DLC tables, so all of them merge — as the project
//     and tech name bakes do.
//
// OUTPUT: src/lib/generated/promotion-names.ts (checked in, self-contained —
// no .bake sidecar, so bake:finalize never wipes it when this hasn't run, the
// same arrangement bake-character-opinion.ts uses).
//
// Only entries whose resolved name DIFFERS from the runtime formatEnum()
// fallback are emitted, matching the tech / project / nation name bakes: an
// ordinary promotion falls through without a lookup, and the table stays
// honest when a patch renames one.
//
// Run: npm run bake:promotion-names

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { XMLParser } from "fast-xml-parser";
import { format as prettierFormat, resolveConfig } from "prettier";

import { resolveReferenceXml } from "./lib/paths.js";
import { formatEnum, stripMarkup } from "../src/lib/utils/formatting.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const OUTPUT_TS = resolve(REPO_ROOT, "src/lib/generated/promotion-names.ts");

interface PromotionEntry {
	zType?: string;
	Name?: string;
}
interface TextEntry {
	zType?: string;
	"en-US"?: string;
}

const parser = new XMLParser({
	ignoreAttributes: true,
	parseTagValue: false,
	ignoreDeclaration: true,
	ignorePiTags: true,
});

async function loadEntries<T>(path: string): Promise<T[]> {
	const xml = await readFile(path, "utf-8");
	const parsed = parser.parse(xml) as { Root?: { Entry?: T | T[] } };
	const entry = parsed.Root?.Entry;
	if (entry == null) return [];
	return Array.isArray(entry) ? entry : [entry];
}

function emit(overrides: Record<string, string>): string {
	const lines = [
		"// AUTO-GENERATED by scripts/bake-promotion-names.ts from",
		"// Reference/XML/Infos (promotion.xml, text-*.xml). Do not edit by hand —",
		"// re-run `npm run bake:promotion-names`.",
		"//",
		"// Only promotions whose in-game name differs from",
		'// `formatEnum(zType, "PROMOTION_")` — the tiered lines, which the game',
		'// numbers with Roman numerals where formatEnum leaves "Combat1". Read',
		"// through `promotionName()` in $lib/game-detail/helpers, never directly.",
		"",
		"export const PROMOTION_NAMES: Readonly<Record<string, string>> = {",
	];
	for (const key of Object.keys(overrides).sort()) {
		lines.push(`\t${JSON.stringify(key)}: ${JSON.stringify(overrides[key])},`);
	}
	lines.push("};", "");
	return lines.join("\n");
}

async function main(): Promise<void> {
	const infosDir = resolve(resolveReferenceXml(), "Infos");
	const allFiles = await readdir(infosDir);
	const textFiles = allFiles.filter((f) => /^text-.*\.xml$/.test(f));

	const [promotions, textEntries] = await Promise.all([
		loadEntries<PromotionEntry>(resolve(infosDir, "promotion.xml")),
		Promise.all(
			textFiles.map((f) => loadEntries<TextEntry>(resolve(infosDir, f))),
		),
	]);

	const textByKey = new Map<string, string>();
	for (const entries of textEntries) {
		for (const t of entries) {
			if (t.zType && t["en-US"]) textByKey.set(t.zType, t["en-US"]);
		}
	}

	const overrides: Record<string, string> = {};
	let total = 0;
	for (const promotion of promotions) {
		const zType = promotion.zType;
		// The template <Entry> at the head of the file has every tag empty.
		if (!zType || !zType.startsWith("PROMOTION_")) continue;
		total += 1;
		if (!promotion.Name) continue;

		const raw = textByKey.get(promotion.Name);
		if (!raw) continue;

		// en-US packs the grammatical forms into one '~'-separated field; the
		// first segment is the bare noun.
		const display = stripMarkup(raw).split("~")[0]?.trim();
		if (!display) continue;
		if (display === formatEnum(zType, "PROMOTION_")) continue;

		overrides[zType] = display;
	}

	if (total === 0) {
		throw new Error(
			"bake-promotion-names: promotion.xml produced no entries — did the XML move?",
		);
	}

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(emit(overrides), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-promotion-names: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-promotion-names: ${Object.keys(overrides).length} overrides emitted ` +
			`(of ${total} promotions, merged ${textFiles.length} text-*.xml files) → ` +
			OUTPUT_TS.replace(REPO_ROOT + "/", ""),
	);
}

await main();
