// Bake the TRAIT_<zType> → English display name table from the OW reference
// XML so a trait reads as the game names it.
//
// formatEnum() title-cases the internal id, which is wrong for 105 of
// trait.xml's 306 traits in three ways:
//
//   particles and apostrophes  TRAIT_SWORD_OF_THE_GODS → "Sword Of The Gods"
//                              (game: "Sword of the Gods"); TRAIT_FOOLS_RING
//                              → "Fools Ring" ("Fool's Ring") — the
//                              apostrophe has no token to survive in
//   a dropped article          TRAIT_RISING_STAR → "Rising Star"
//                              ("A Rising Star")
//   a developer filing id      TRAIT_CYAXARES_LEADER is "Median
//                              Expansionist", TRAIT_HANNIBAL_LEADER "Grace of
//                              Ba'al", TRAIT_LEONIDAS_LEADER "Indomitable",
//                              TRAIT_CLERGY_JEWISH "Kohen". Not a formatting
//                              difference at all: formatEnum shows the user a
//                              name the game never uses.
//
// SOURCES (local-only, via the Reference/ symlink resolved by paths.ts), under
// Reference/XML/Infos/:
//   trait.xml         — <Entry> with <zType> and <GenderedName>. All 306 go
//     through the gendered indirection; none carries the plain <Name> that
//     promotion.xml uses, so the genderedText walk is not optional here.
//   genderedText*.xml — <Entry> whose <Texts> pairs map a grammatical gender
//     to a TEXT_* key, merged across base and DLC as the nation-name bake
//     does.
//   text-*.xml        — <Entry> with that key and an <en-US> string, likewise
//     merged.
//   tribe.xml         — one trait's name embeds a link: TRAIT_ENVOY_TO_THE_HUNS
//     is "Envoy to the link(TRIBE_HUNS)". Resolved against the tribe's own
//     name rather than through stripMarkup's formatEnum-shaped fallback, the
//     way bake-effect-units.ts resolves its link(TRAIT_*) names, and a link to
//     anything else THROWS rather than being approximated.
//
// OUTPUT: src/lib/generated/trait-names.ts (checked in, self-contained — no
// .bake sidecar, so bake:finalize never wipes it when this hasn't run, the
// arrangement bake-character-opinion.ts and bake-promotion-names.ts use).
// Frontend only: the Worker returns raw TRAIT_* tokens and never labels one
// (cloud/src/stats/aggregate.ts keeps only the _ARCHETYPE suffix rule), so
// there is nothing for a cloud/src/generated/ copy to do.
//
// Only entries whose resolved name DIFFERS from the runtime formatEnum()
// fallback are emitted, matching the promotion / tech / project / nation name
// bakes: an ordinary trait falls through without a lookup, and the table stays
// honest when a patch renames one.
//
// Run: npm run bake:trait-names

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { XMLParser } from "fast-xml-parser";
import { format as prettierFormat, resolveConfig } from "prettier";

import { resolveReferenceXml } from "./lib/paths.js";
import { formatEnum, stripMarkup } from "../src/lib/utils/formatting.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const OUTPUT_TS = resolve(REPO_ROOT, "src/lib/generated/trait-names.ts");

// The gender whose text is the plain trait name; a feminine row is the same
// name declined for a female character.
const MASCULINE = "GRAMMATICAL_GENDER_MASCULINE";

interface NamedEntry {
	zType?: string;
	GenderedName?: string;
}
interface GenderedPair {
	zIndex?: string;
	zValue?: string;
}
interface GenderedTextEntry {
	zType?: string;
	Texts?: { Pair?: GenderedPair | GenderedPair[] };
}
interface TextEntry {
	zType?: string;
	"en-US"?: string;
}

const parser = new XMLParser({
	ignoreAttributes: true,
	parseTagValue: false,
	ignoreDeclaration: true,
	ignorePiTags: true,
});

async function loadEntries<T>(path: string): Promise<T[]> {
	const xml = await readFile(path, "utf-8");
	const parsed = parser.parse(xml) as { Root?: { Entry?: T | T[] } };
	const entry = parsed.Root?.Entry;
	if (entry == null) return [];
	return Array.isArray(entry) ? entry : [entry];
}

function emit(overrides: Record<string, string>): string {
	const lines = [
		"// AUTO-GENERATED by scripts/bake-trait-names.ts from Reference/XML/Infos",
		"// (trait.xml, genderedText*.xml, text-*.xml, tribe.xml). Do not edit by",
		"// hand — re-run `npm run bake:trait-names`.",
		"//",
		"// Only traits whose in-game name differs from",
		'// `formatEnum(zType, "TRAIT_")` — the ones carrying a lowercase particle',
		"// or apostrophe, an article, or a developer filing id that is no kind of",
		"// name at all. Read through `traitName()` in $lib/utils/formatting, never",
		"// directly.",
		"",
		"export const TRAIT_NAMES: Readonly<Record<string, string>> = {",
	];
	for (const key of Object.keys(overrides).sort()) {
		lines.push(`\t${JSON.stringify(key)}: ${JSON.stringify(overrides[key])},`);
	}
	lines.push("};", "");
	return lines.join("\n");
}

async function main(): Promise<void> {
	const infosDir = resolve(resolveReferenceXml(), "Infos");
	const allFiles = await readdir(infosDir);
	const textFiles = allFiles.filter((f) => /^text-.*\.xml$/.test(f));
	const genderedFiles = allFiles.filter((f) => /^genderedText.*\.xml$/.test(f));

	const [traits, tribes, genderedEntries, textEntries] = await Promise.all([
		loadEntries<NamedEntry>(resolve(infosDir, "trait.xml")),
		loadEntries<NamedEntry>(resolve(infosDir, "tribe.xml")),
		Promise.all(
			genderedFiles.map((f) =>
				loadEntries<GenderedTextEntry>(resolve(infosDir, f)),
			),
		),
		Promise.all(
			textFiles.map((f) => loadEntries<TextEntry>(resolve(infosDir, f))),
		),
	]);

	const textKeyByGendered = new Map<string, string>();
	for (const entries of genderedEntries) {
		for (const g of entries) {
			if (!g.zType) continue;
			const pairs = g.Texts?.Pair;
			if (pairs == null) continue;
			const list = Array.isArray(pairs) ? pairs : [pairs];
			const masculine = list.find((p) => p.zIndex === MASCULINE);
			if (masculine?.zValue && !textKeyByGendered.has(g.zType)) {
				textKeyByGendered.set(g.zType, masculine.zValue);
			}
		}
	}

	const textByKey = new Map<string, string>();
	for (const entries of textEntries) {
		for (const t of entries) {
			if (t.zType && t["en-US"] && !textByKey.has(t.zType)) {
				textByKey.set(t.zType, t["en-US"]);
			}
		}
	}

	// en-US packs the grammatical forms into one '~'-separated field; the first
	// segment is the bare noun, which is what a label wants. 28 traits carry
	// the extra forms ("Elect~one of the Elect~the Elects").
	const displayFor = (entry: NamedEntry): string | null => {
		const key = entry.GenderedName
			? textKeyByGendered.get(entry.GenderedName)
			: undefined;
		const raw = key ? textByKey.get(key) : undefined;
		if (!raw) return null;
		const bare = raw.split("~")[0] ?? "";
		return bare.trim() !== "" ? bare : null;
	};

	const tribeNames = new Map<string, string>();
	for (const tribe of tribes) {
		if (!tribe.zType) continue;
		const display = displayFor(tribe);
		if (display) tribeNames.set(tribe.zType, stripMarkup(display).trim());
	}

	const overrides: Record<string, string> = {};
	let total = 0;
	let linked = 0;
	for (const trait of traits) {
		const zType = trait.zType;
		// The template <Entry> at the head of the file has every tag empty.
		if (!zType || !zType.startsWith("TRAIT_")) continue;
		total += 1;

		const bare = displayFor(trait);
		if (!bare) continue;

		// Resolve an embedded link against the linked thing's OWN name before
		// stripMarkup can approximate it from the token. Wired to tribe.xml and
		// nothing else: today that is TRAIT_ENVOY_TO_THE_HUNS alone, and a link
		// to another kind of thing should fail the bake rather than ship a
		// guess.
		const resolved = bare.replace(
			/link\(([A-Z0-9_]+)(?:,[^)]*)?\)/g,
			(_, target: string) => {
				const name = tribeNames.get(target);
				if (name == null) {
					throw new Error(
						`bake-trait-names: ${zType}'s name links to ${target}, which ` +
							"tribe.xml does not hold — widen the link resolver to the " +
							"table that does",
					);
				}
				linked += 1;
				return name;
			},
		);

		const display = stripMarkup(resolved).trim();
		if (!display) continue;
		if (display === formatEnum(zType, "TRAIT_")) continue;

		overrides[zType] = display;
	}

	if (total === 0) {
		throw new Error(
			"bake-trait-names: trait.xml produced no entries — did the XML move?",
		);
	}

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(emit(overrides), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-trait-names: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-trait-names: ${Object.keys(overrides).length} overrides emitted ` +
			`(of ${total} traits, ${linked} name(s) resolved through a link, ` +
			`merged ${genderedFiles.length} genderedText*.xml and ` +
			`${textFiles.length} text-*.xml files) → ` +
			OUTPUT_TS.replace(REPO_ROOT + "/", ""),
	);
}

await main();
