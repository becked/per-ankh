// Bake the two legs that turn a tribe into the crest the game draws for it, so
// a city no player holds wears the game's own badge instead of an empty slot.
//
// NEITHER LEG IS A NAMING RULE — that is the whole reason this table exists:
//
//   tribe → crest.  tribe.xml's <Crest> is CREST_<zType> for 10 of the 11 base
//     tribes and then isn't: TRIBE_BARBARIANS wears CREST_TRIBE_GENERIC. The
//     campaign tribes break it outright — TRIBE_BERBERS wears
//     CREST_TRIBE_THRACIANS, TRIBE_PLATAEA wears CREST_TRIBE_GAULS, and
//     EgyptCampaign's tribe-change.xml moves TRIBE_SCYTHIANS onto
//     CREST_NATION_KUSH. So this leg is emitted WHOLE.
//
//   crest → sprite.  crest.xml's <zSpriteName> is the art the crest resolves
//     to, and it is not the crest's own name for 26 of the merged entries:
//     CREST_TRIBE_ANARCHY and CREST_TRIBE_RAIDERS both draw
//     CREST_TRIBE_REBELS, the 20 CREST_FAMILYCLASS_* rows draw
//     CREST_ARCHETYPE_*, and the campaign files add four more. Only the
//     entries whose sprite name DIFFERS are emitted, matching the name bakers
//     and bake-project-icons: a crest that names its own art falls through to
//     its zType without a lookup.
//
// `City.getCrest` (City.cs:3319) returns `tribeInfo().meCrest` for a city whose
// tribe is set, which is every city under capture — `Unit.doCityCapture`
// (Unit.cs:2004) hands the city to nobody under TRIBE_ANARCHY. Walking both
// legs is what gets from that tribe to crests/CREST_TRIBE_REBELS, which we
// already ship.
//
// SOURCES (local-only, via the Reference/ symlink resolved by paths.ts):
//   Reference/XML/Infos/crest.xml — <zType> → <zSpriteName>.
//   Reference/XML/Infos/tribe.xml — <Crest> per tribe.
//   Mods/*/Infos/{crest,tribe}-{add,change}.xml — the campaign/scenario
//     content, merged last-wins by zType with per-field updates
//     (scripts/lib/reference-xml.ts, shared with bake-civilization-colors).
//     Uploaded campaign saves carry these tribes.
//
// OUTPUT: src/lib/generated/crest-sprites.ts (checked in, self-contained).
//
// Run: npm run bake:crest-sprites

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { format as prettierFormat, resolveConfig } from "prettier";

import { loadMergedEntries } from "./lib/reference-xml.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const OUTPUT_TS = resolve(REPO_ROOT, "src/lib/generated/crest-sprites.ts");

interface CrestEntry {
	zType?: string;
	zSpriteName?: string;
}

interface TribeEntry {
	zType?: string;
	Crest?: string;
}

function sortKeys(t: Record<string, string>): Record<string, string> {
	return Object.fromEntries(
		Object.keys(t)
			.sort()
			.map((k) => [k, t[k]]),
	);
}

async function main(): Promise<void> {
	const [crests, tribes] = await Promise.all([
		loadMergedEntries<CrestEntry>("crest"),
		loadMergedEntries<TribeEntry>("tribe"),
	]);

	// Only the indirect rows — see the crest → sprite note above.
	const spriteNames: Record<string, string> = {};
	for (const [zType, crest] of crests) {
		if (!crest.zSpriteName || crest.zSpriteName === zType) continue;
		spriteNames[zType] = crest.zSpriteName;
	}

	// Every tribe, direct or not. A tribe with no <Crest> would leave a city it
	// holds with no badge at all, which is a parse miss rather than a game
	// fact — the base roster all carry one.
	const tribeCrests: Record<string, string> = {};
	for (const [zType, tribe] of tribes) {
		if (!tribe.Crest) {
			if (tribe.inBase) {
				throw new Error(
					`bake-crest-sprites: base tribe ${zType} declares no <Crest> — did tribe.xml parse?`,
				);
			}
			console.warn(
				`bake-crest-sprites: WARN campaign tribe ${zType} has no crest`,
			);
			continue;
		}
		tribeCrests[zType] = tribe.Crest;
	}
	if (Object.keys(tribeCrests).length === 0) {
		throw new Error("bake-crest-sprites: no tribe resolved a crest");
	}
	if (Object.keys(spriteNames).length === 0) {
		throw new Error(
			"bake-crest-sprites: crest.xml yielded no indirect sprite name — did it parse?",
		);
	}

	const lines: string[] = [];
	lines.push(
		"// AUTO-GENERATED by scripts/bake-crest-sprites.ts. Do not edit.",
	);
	lines.push(
		"// Run `npm run bake:crest-sprites` to refresh from Reference/XML.",
	);
	lines.push("");
	lines.push("// Tribe → the crest the game draws for it (tribe.xml <Crest>).");
	lines.push(
		"// Emitted whole: the value is CREST_<zType> for most of the base",
	);
	lines.push(
		"// roster and for almost none of the campaign tribes, so there is",
	);
	lines.push("// no rule to fall back on.");
	lines.push(
		`export const TRIBE_CRESTS: Readonly<Record<string, string>> = ${JSON.stringify(sortKeys(tribeCrests))};`,
	);
	lines.push("");
	lines.push("// Crest → the sprite its art actually ships under (crest.xml");
	lines.push("// <zSpriteName>), for the entries where the two differ —");
	lines.push("// CREST_TRIBE_ANARCHY draws CREST_TRIBE_REBELS. A crest absent");
	lines.push("// here names its own art.");
	lines.push(
		`export const CREST_SPRITE_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(sortKeys(spriteNames))};`,
	);
	lines.push("");

	const config = await resolveConfig(OUTPUT_TS);
	const formatted = await prettierFormat(lines.join("\n"), {
		...config,
		parser: "typescript",
		filepath: OUTPUT_TS,
	});
	await mkdir(dirname(OUTPUT_TS), { recursive: true });
	if (existsSync(OUTPUT_TS)) {
		const existing = await readFile(OUTPUT_TS, "utf-8");
		if (existing === formatted) {
			console.log("bake-crest-sprites: no changes");
			return;
		}
	}
	await writeFile(OUTPUT_TS, formatted);
	console.log(
		`bake-crest-sprites: ${Object.keys(tribeCrests).length} tribe crests + ${Object.keys(spriteNames).length} indirect sprite names (of ${crests.size} crests) → ${OUTPUT_TS.replace(REPO_ROOT + "/", "")}`,
	);
}

await main();
